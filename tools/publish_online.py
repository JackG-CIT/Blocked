"""Publishes the standalone game to the online repo (JackG-CIT/BlockedV2), whose
GitHub Pages site is https://jackg-cit.github.io/BlockedV2/.

    cd tools
    ..\\.venv\\Scripts\\python publish_online.py            # build, then publish
    ..\\.venv\\Scripts\\python publish_online.py --dry-run  # build and stage, but don't push

It rebuilds dist/standalone (the same as `flask --app app export-standalone`),
clones the online repo into a temp folder, replaces its files with the build,
commits and pushes. GitHub Pages republishes a minute or so later.
"""
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
ONLINE = 'https://github.com/JackG-CIT/BlockedV2.git'
SOURCE = 'https://github.com/JackG-CIT/Blocked'
PLAY = 'https://jackg-cit.github.io/BlockedV2/'

README = f"""# Blocked (play online)

**Play it here: {PLAY}**

A pixel-art pirate puzzle game: push crates, trip plates, squeeze crates through
slamming gates, fire cannons, and find the treasure. This repository only holds
the built game that GitHub Pages serves. The source code (the Flask community
site, the level tools and the build script) lives at {SOURCE}.

This folder is generated by `tools/publish_online.py` in the source repo; don't
edit it by hand.
"""


def git(*args, cwd):
    subprocess.run(['git', *args], cwd=cwd, check=True)


def main():
    dry = '--dry-run' in sys.argv
    sys.path.insert(0, ROOT)
    os.chdir(ROOT)
    os.environ.setdefault('DATABASE_URL', '')
    import app as site
    import export_standalone
    build, _, size = export_standalone.export(site.app, {'min': site.MIN_SIZE, 'max': site.MAX_SIZE})
    print(f'built {build} ({size / 1024:.0f} KB zipped)')

    tmp = tempfile.mkdtemp(prefix='blocked-online-')
    try:
        git('clone', '--depth', '1', ONLINE, tmp, cwd=ROOT)
        for name in os.listdir(tmp):
            if name == '.git':
                continue
            path = os.path.join(tmp, name)
            shutil.rmtree(path) if os.path.isdir(path) else os.remove(path)
        shutil.copytree(build, tmp, dirs_exist_ok=True)
        open(os.path.join(tmp, '.nojekyll'), 'w').close()   # serve files as they are
        with open(os.path.join(tmp, 'README.md'), 'w', encoding='utf-8') as f:
            f.write(README)
        # Commit as the source repo's author.
        for key in ('user.name', 'user.email'):
            value = subprocess.run(['git', 'config', key], cwd=ROOT, capture_output=True, text=True).stdout.strip()
            if value:
                git('config', key, value, cwd=tmp)
        git('add', '-A', cwd=tmp)
        if not subprocess.run(['git', 'status', '--porcelain'], cwd=tmp, capture_output=True, text=True).stdout.strip():
            print('nothing changed since the last publish')
            return
        git('commit', '-q', '-m', 'Publish the standalone game', cwd=tmp)
        if dry:
            print(f'dry run: staged in {tmp}, not pushed')
            return
        git('push', '-q', 'origin', 'HEAD:main', cwd=tmp)
        print(f'published: {PLAY} (GitHub Pages updates in a minute or so)')
    finally:
        if not dry:
            shutil.rmtree(tmp, ignore_errors=True)


if __name__ == '__main__':
    main()
